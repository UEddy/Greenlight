/**
 * The curated JSON from data/processed/, imported rather than read.
 *
 * Nothing here reads data/raw/. Nothing here reaches the network. The four
 * files are the only source of every number this service will ever put in
 * front of a user.
 *
 * These are static imports, not readFileSync, and that is a deployment
 * decision rather than a style one. Reading them from disk meant computing a
 * path from import.meta.url and hoping the same relative layout existed at
 * runtime. That holds locally and is exactly the thing that breaks once the
 * code is bundled into a serverless function, where the file is somewhere
 * else and the data directory was never traced as a dependency. A static
 * import makes the bundler responsible: the data is part of the module graph,
 * so it either builds or fails at build time, and it can never be missing at
 * request time. All four files together are well under a megabyte.
 */

import financialJson from "../../data/processed/financial-requirements.json" with { type: "json" };
import schengenJson from "../../data/processed/schengen-consulate-not-issued.json" with { type: "json" };
import ukJson from "../../data/processed/uk-visitor-refusals.json" with { type: "json" };
import usJson from "../../data/processed/us-b-visa-refusals.json" with { type: "json" };

